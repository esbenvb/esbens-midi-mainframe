#!/usr/bin/env bash
# Generate image/configs/emm_<name>_defconfig from defconfig.d/.
# Two kinds of build, so two kinds of config:
#   userland   the system every board runs (no kernel): defconfig.d/userland.defconfig
#   rpi3|rpi4|rpi5   one board's kernel, device trees, modules and firmware:
#              defconfig.d/kernel-common.defconfig + defconfig.d/<board>.defconfig
# Buildroot defconfigs cannot include each other, so the shared part is kept
# once in kernel-common.defconfig and pasted into each board's file.
#
#   image/mkconfigs.sh           regenerate the committed files
#   image/mkconfigs.sh --check   fail if they are out of date (for CI / pre-commit)
set -euo pipefail

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
check=0
case "${1:-}" in
  "") ;;
  --check) check=1 ;;
  -h|--help)
    # The leading comment block, without the "# ".
    awk 'NR == 1 { next } /^#/ { sub(/^# ?/, ""); print; next } { exit }' "${BASH_SOURCE[0]}"
    exit 0 ;;
  *) echo "mkconfigs.sh: unknown option: $1 (see --help)" >&2; exit 2 ;;
esac
mkdir -p "$here/configs"
rc=0
# emit NAME SOURCE...: write (or check) configs/emm_NAME_defconfig from the source files.
emit() {
  local name=$1; shift
  local out="$here/configs/emm_${name}_defconfig" tmp f first=1 list=""
  for f in "$@"; do list="${list:+$list, }${f%.defconfig}"; done
  tmp=$(mktemp)
  {
    echo "# GENERATED by image/mkconfigs.sh from image/defconfig.d/{$list}.defconfig."
    echo "# Do not edit this file; edit the sources and run image/mkconfigs.sh."
    for f in "$@"; do
      echo
      cat "$here/defconfig.d/$f"
    done
  } > "$tmp"
  if [ "$check" = 1 ]; then
    if ! cmp -s "$tmp" "$out"; then
      echo "out of date: $out (run image/mkconfigs.sh)" >&2
      rc=1
    fi
    rm -f "$tmp"
  else
    chmod 0644 "$tmp"   # mktemp makes it 0600
    mv "$tmp" "$out"
    echo "wrote $out"
  fi
}
emit userland userland.defconfig
for board in rpi3 rpi4 rpi5; do
  emit "$board" kernel-common.defconfig "$board.defconfig"
done
exit "$rc"
