#!/usr/bin/env bash
# Generate image/configs/emm_<board>_defconfig from defconfig.d/.
# Buildroot defconfigs cannot include each other, so the shared part is kept
# once in defconfig.d/common.defconfig and pasted into each board's file.
#
#   image/mkconfigs.sh           regenerate the committed files
#   image/mkconfigs.sh --check   fail if they are out of date (for CI / pre-commit)
set -euo pipefail

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
check=0
case "${1:-}" in
  "") ;;
  --check) check=1 ;;
  -h|--help)
    # The leading comment block, without the "# ".
    awk 'NR == 1 { next } /^#/ { sub(/^# ?/, ""); print; next } { exit }' "${BASH_SOURCE[0]}"
    exit 0 ;;
  *) echo "mkconfigs.sh: unknown option: $1 (see --help)" >&2; exit 2 ;;
esac
mkdir -p "$here/configs"
rc=0
for board in rpi4 rpi5; do
  out="$here/configs/emm_${board}_defconfig"
  tmp=$(mktemp)
  {
    echo "# GENERATED by image/mkconfigs.sh from image/defconfig.d/{common,$board}.defconfig."
    echo "# Do not edit this file; edit the sources and run image/mkconfigs.sh."
    echo
    cat "$here/defconfig.d/common.defconfig"
    echo
    cat "$here/defconfig.d/$board.defconfig"
  } > "$tmp"
  if [ "$check" = 1 ]; then
    if ! cmp -s "$tmp" "$out"; then
      echo "out of date: $out (run image/mkconfigs.sh)" >&2
      rc=1
    fi
    rm -f "$tmp"
  else
    chmod 0644 "$tmp"   # mktemp makes it 0600
    mv "$tmp" "$out"
    echo "wrote $out"
  fi
done
exit "$rc"
